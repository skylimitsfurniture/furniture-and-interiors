/**
 * Currency Formatter (INR)
 */
export function formatINR(amount) {
  return new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0,
  }).format(amount);
}

/**
 * Filter items by search query across title, category, subcategory, tags, etc.
 */
export function searchFurniture(query) {
  const q = (query || "").trim().toLowerCase();
  if (!q) return [];
  return furnitureData.filter((p) => {
    const haystack = [
      p.title,
      p.name,
      p.category,
      p.section,
      p.subcategory,
      p.material,
      ...(p.tags || []),
    ]
      .join(" ")
      .toLowerCase();
    return haystack.includes(q);
  });
}

/**
 * Get product by ID
 */
export function getFurnitureById(id) {
  return furnitureData.find((p) => p.id === id);
}

/**
 * Get items by subcategory
 */
export function getFurnitureBySubcategory(subcategoryName) {
  return furnitureData.filter(
    (p) => p.subcategory?.toLowerCase() === subcategoryName?.toLowerCase()
  );
}
